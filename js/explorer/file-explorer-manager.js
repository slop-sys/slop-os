export class FileExplorerManager {
  constructor(options = {}) {
    this.playClickSound = typeof options.playClickSound === 'function' ? options.playClickSound : () => {};
    this.onEvidenceFound = typeof options.onEvidenceFound === 'function' ? options.onEvidenceFound : () => {};
    this.fileData = FILE_EXPLORER_DATA;

    this.folders = [];
    this.explorerContent = null;
    this.explorerPath = null;
    this.fileCount = null;
  }

  setup() {
    this.folders = Array.from(document.querySelectorAll('.explorer-folder'));
    this.explorerContent = document.getElementById('explorer-content');
    this.explorerPath = document.getElementById('explorer-path');
    this.fileCount = document.getElementById('file-count');

    if (!this.folders.length || !this.explorerContent || !this.explorerPath || !this.fileCount) {
      return;
    }

    this.folders.forEach((folder) => {
      folder.addEventListener('click', () => {
        this.playClickSound();
        this.openFolder(folder.dataset.folder, folder);
      });
    });
  }

  openFolder(folderName, selectedFolderEl = null) {
    if (!folderName) return;

    const data = this.fileData[folderName];
    if (!data || !this.explorerContent || !this.explorerPath || !this.fileCount) {
      return;
    }

    this.explorerPath.textContent = `C:\\SLOP\\SYSTEM\\${data.name}`;
    this.fileCount.textContent = data.files.length;

    this.folders.forEach((folder) => folder.classList.remove('selected'));
    if (selectedFolderEl) {
      selectedFolderEl.classList.add('selected');
    }

    this.renderFileList(data.files);
  }

  renderFileList(files) {
    this.explorerContent.innerHTML = `
      <div class="explorer-file-header">
        <span>Name</span>
        <span>Type</span>
        <span>Size</span>
        <span>Modified</span>
      </div>
    `;

    files.forEach((file) => {
      const fileEl = document.createElement('div');
      fileEl.className = 'explorer-file-item';

      fileEl.innerHTML = `
        <div class="explorer-file-row">
          <div class="explorer-file-name-wrap">
            <img src="${this.resolveFileIcon(file.name)}" alt="">
            <span class="explorer-file-name">${file.name}</span>
          </div>
          <div class="explorer-file-cell">${file.type}</div>
          <div class="explorer-file-cell">${file.size}</div>
          <div class="explorer-file-cell">${file.modified}</div>
        </div>
      `;

      fileEl.addEventListener('click', () => {
        this.playClickSound();

        const explorerItems = this.explorerContent.querySelectorAll('.explorer-file-item');
        explorerItems.forEach((item) => item.classList.remove('selected'));
        fileEl.classList.add('selected');

        this.openFile(file);
      });

      this.explorerContent.appendChild(fileEl);
    });
  }

  resolveFileIcon(fileName) {
    if (fileName.endsWith('.csv') || fileName.endsWith('.json')) {
      return 'icons/document-0.png';
    }

    return 'icons/notepad_file-0.png';
  }

  openFile(file) {
    const evidenceKey = FILE_VIEWER_EVIDENCE_MAP[file.name];
    if (evidenceKey) {
      this.onEvidenceFound(evidenceKey);
    }

    this.showFileViewer(file);
  }

  showFileViewer(file) {
    const viewer = document.createElement('div');
    viewer.className = 'file-viewer-overlay';

    viewer.innerHTML = `
      <div class="file-viewer-titlebar">
        <span style="font-size: 11px; font-weight: bold;">${file.name}</span>
        <button class="file-viewer-close" style="background: #c0c0c0; border: 1px outset #fff; padding: 0 6px; cursor: pointer; font-weight: bold;">?</button>
      </div>
      <div class="file-viewer-content">
${file.content}
      </div>
      <div class="file-viewer-statusbar">
        <span>${file.name} - ${file.size} - ${file.modified}</span>
      </div>
    `;

    document.body.appendChild(viewer);

    const closeBtn = viewer.querySelector('.file-viewer-close');
    const closeViewer = () => {
      this.playClickSound();
      viewer.remove();
      document.removeEventListener('mousemove', onMouseMove);
      document.removeEventListener('mouseup', onMouseUp);
    };

    if (closeBtn) {
      closeBtn.addEventListener('click', closeViewer);
    }

    const titleBar = viewer.querySelector('.file-viewer-titlebar');
    let isDragging = false;
    let startX = 0;
    let startY = 0;
    let startLeft = 0;
    let startTop = 0;

    const onMouseMove = (e) => {
      if (!isDragging) return;

      const dx = e.clientX - startX;
      const dy = e.clientY - startY;
      viewer.style.left = `${startLeft + dx}px`;
      viewer.style.top = `${startTop + dy}px`;
      viewer.style.transform = 'none';
    };

    const onMouseUp = () => {
      isDragging = false;
    };

    if (titleBar) {
      titleBar.addEventListener('mousedown', (e) => {
        isDragging = true;
        startX = e.clientX;
        startY = e.clientY;
        startLeft = viewer.offsetLeft;
        startTop = viewer.offsetTop;
      });
    }

    document.addEventListener('mousemove', onMouseMove);
    document.addEventListener('mouseup', onMouseUp);
  }
}

export default FileExplorerManager;
